#!/usr/bin/env bash
# Gate for a regenerated keen. Every step must pass before the branch is merged.
#   scripts/regen/check.sh
# Set KEEN_LIVE_SMOKE=<script> to also run a live smoke test against a real site.
set -uo pipefail
REPO=$(git rev-parse --show-toplevel)
cd "$REPO"
# shellcheck source=/dev/null
source scripts/regen/config.sh
fail=0
step() { printf '%-44s ' "$1"; shift; if out=$("$@" 2>&1); then echo PASS; else echo FAIL; echo "$out" | tail -20; fail=1; fi; }

names() {
  # Old names anywhere outside history notes, specs and this config.
  ! git grep -n -I -E "$OLD_NAMES" -- . ':!specs' ':!CHANGELOG.md' ':!scripts/regen' ':!.printing-press-patches.json' \
      ':!**/*_test.go' | grep -v 'Generated by CLI Printing Press' | grep -v 'github.com/mvanhorn/cli-printing-press'
}
help_text() {
  # Every command keen which lists: --help works and says nothing about the old names.
  go build -o "$BIN/keen" ./cmd/keen || return 1
  python3 - "$BIN/keen" "$OLD_NAMES" <<'PY'
import re, subprocess, sys
keen, old = sys.argv[1], re.compile(sys.argv[2])
src = open("internal/cli/which.go").read()
cmds = re.findall(r'\{Command: "([^"]+)"', src)
bad = []
for c in cmds:
    r = subprocess.run([keen, *c.split(), "--help"], capture_output=True, text=True)
    if r.returncode != 0 or "unknown command" in r.stderr or old.search(r.stdout + r.stderr):
        bad.append(c)
print(f"{len(cmds)} commands checked, {len(bad)} bad")
for c in bad[:30]:
    print("  ", c)
sys.exit(1 if bad else 0)
PY
}
BIN=$(mktemp -d "${TMPDIR:-/tmp}/keen-check-XXXX")

step "go build"                      go build ./...
step "go vet"                        go vet ./...
step "go test"                       go test ./...
step "golangci-lint"                 make lint
step "govulncheck"                   govulncheck ./...
step "no old names in the tree"      names
step "every command's help is clean" help_text
step "binaries build as keen"        bash -c "go build -o '$BIN/keen' ./cmd/keen && go build -o '$BIN/keen-mcp' ./cmd/keen-mcp && '$BIN/keen' version"
if [[ -n "${KEEN_LIVE_SMOKE:-}" ]]; then
  step "live smoke test"             bash -c "bash '$KEEN_LIVE_SMOKE' '$BIN' | tee /dev/stderr | grep -q 'failures: 0'"
fi
[[ $fail -eq 0 ]] && echo "check: all passed" || echo "check: FAILED"
exit $fail
