#!/usr/bin/env python3
"""List the API operations Atlassian marks deprecated.

Atlassian keeps deprecated and even removed operations in its specs (GET
/rest/api/3/search answers 410 but is still listed), so keen generates
commands and MCP tools for them. This writes internal/compat/deprecated_gen.go:
each deprecated operation as "METHOD path" (path as keen's commands carry it,
parameter names dropped), whether the spec says it is being removed, and the
MCP tools that call one. The CLI labels those commands; keen_search ranks the
tools last and labels them.

    scripts/regen/deprecated.py     # regen.sh runs it after generating
"""
import json
import pathlib
import re
import subprocess

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = REPO / "internal" / "compat" / "deprecated_gen.go"
TOOLS = REPO / "internal" / "mcp" / "tools.go"
PARAM = re.compile(r"\{[^}]*\}")
TOOL = re.compile(r'NewTool\("([^"]+)".*?makeAPIHandler\("([A-Z]+)", "([^"]+)"', re.S)
METHODS = ("get", "put", "post", "delete", "patch")


def spec_names():
    out = subprocess.run(["bash", "-c", 'source scripts/regen/config.sh && printf "%s\\n" "${SPECS[@]}"'],
                         cwd=REPO, capture_output=True, text=True, check=True).stdout
    return [line.split("=", 1)[0] for line in out.splitlines() if line]


def command_path(server, path):
    """The path keen's generated commands carry for an operation."""
    host, _, base = server.partition("//")[2].partition("/")
    base = "/" + base.rstrip("/") if base else ""
    if "{" in host or "your-domain" in host or not host:
        return endpoint_key("", base + path)  # on the customer's site: relative
    return endpoint_key("", "https://" + host + base + path)


def endpoint_key(method, path):
    return (method + " " if method else "") + PARAM.sub("{}", path)


def main():
    entries = {}
    for name in spec_names():
        spec = json.loads((REPO / "specs" / f"{name}.json").read_text())
        server = (spec.get("servers") or [{"url": ""}])[0]["url"]
        if "{" in server.partition("//")[2].partition("/")[2]:
            continue  # server path ids become markers; no deprecated operations there today
        for path, item in spec["paths"].items():
            for method, op in item.items():
                if method not in METHODS:
                    continue
                removing = "being removed" in (op.get("description") or "").lower()
                if op.get("deprecated") or removing:
                    entries[f"{method.upper()} {command_path(server, path)}"] = removing
    tools = {}
    for name, method, path in TOOL.findall(TOOLS.read_text()):
        key = endpoint_key(method, path)
        if key in entries:
            tools[name] = key
    lines = ["// Code generated by scripts/regen/deprecated.py from specs/. DO NOT EDIT.", "",
             "package compat", "",
             "// DeprecatedEndpoints maps \"METHOD path\" (path parameters written {}) to",
             "// true when Atlassian says the operation is being removed, false when it is",
             "// only deprecated.",
             "var DeprecatedEndpoints = map[string]bool{"]
    lines += [f"\t{json.dumps(k)}: {'true' if v else 'false'}," for k, v in sorted(entries.items())]
    lines += ["}", "", "// DeprecatedTools maps each MCP tool that calls a deprecated operation to it.",
              "var DeprecatedTools = map[string]string{"]
    lines += [f"\t{json.dumps(k)}: {json.dumps(v)}," for k, v in sorted(tools.items())]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    subprocess.run(["gofmt", "-w", str(OUT)], check=True)
    print(f"deprecated: {len(entries)} operations, {len(tools)} MCP tools -> {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
