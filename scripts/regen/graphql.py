#!/usr/bin/env python3
"""Keep keen's Teamwork Graph commands in step with Atlassian's GraphQL schema.

Atlassian's org chart and Teamwork Graph queries (teamworkGraph_userManager,
teamworkGraph_userTeams, ...) exist only on the GraphQL gateway, not in any
OpenAPI spec. This reads the schema (introspection needs no login), keeps a
snapshot in specs/graphql.json, and writes the table the hand-written commands
in internal/cli/teamwork_graph.go are built from.

    scripts/regen/graphql.py --write   # refresh specs/graphql.json and the Go table
    scripts/regen/graphql.py --check   # compare the live schema with the snapshot;
                                       # prints what changed, exit 1 when anything did

regen.sh runs --write; specdiff.py runs --check. Which fields are covered is
GRAPHQL_PREFIXES in config.sh.
"""
import json
import pathlib
import re
import subprocess
import sys
import urllib.request

REPO = pathlib.Path(__file__).resolve().parents[2]
ENDPOINT = "https://api.atlassian.com/graphql"
SNAPSHOT = REPO / "specs" / "graphql.json"
TABLE = REPO / "internal" / "cli" / "teamwork_graph_gen.go"

TYPE = "type { kind name ofType { kind name ofType { kind name ofType { kind name } } } }"
QUERY = ("query KeenSchema { __schema { queryType { fields { name description "
         "args { name description " + TYPE + " } " + TYPE + " } } } }")
OPT_IN = re.compile(r'@optIn\(to:\s*\\?"([^"\\]+)')


def prefixes():
    out = subprocess.run(
        ["bash", "-c", 'source scripts/regen/config.sh && printf "%s\\n" "${GRAPHQL_PREFIXES[@]}"'],
        cwd=REPO, capture_output=True, text=True, check=True).stdout
    return [p for p in out.split() if p]


def type_string(t):
    if t["kind"] == "NON_NULL":
        return type_string(t["ofType"]) + "!"
    if t["kind"] == "LIST":
        return "[" + type_string(t["ofType"]) + "]"
    return t["name"]


def live_fields():
    req = urllib.request.Request(ENDPOINT, data=json.dumps({"operationName": "KeenSchema", "query": QUERY}).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        schema = json.load(r)["data"]["__schema"]["queryType"]["fields"]
    keep = prefixes()
    fields = []
    for f in schema:
        if not any(f["name"].startswith(p) for p in keep):
            continue
        desc = f["description"] or ""
        m = OPT_IN.search(desc)
        fields.append({
            "name": f["name"],
            "summary": first_sentence(desc) or command_name(f["name"]).replace("-", " ").capitalize() + " (Teamwork Graph).",
            "optIn": m.group(1) if m else "",
            "forceDynamo": "X-Force-Dynamo" in desc,
            "returns": type_string(f["type"]),
            "args": [{"name": a["name"], "type": type_string(a["type"])} for a in f["args"]],
        })
    return sorted(fields, key=lambda f: f["name"])


def first_sentence(desc):
    text = desc.split("###")[0].strip().replace("\n", " ")
    m = re.match(r"(.+?\.)(\s|$)", text)
    return (m.group(1) if m else text)[:200]


def command_name(field):
    name = field.split("_", 1)[1]
    name = re.sub(r"V\d+$", "", name)
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def go_string(s):
    return json.dumps(s, ensure_ascii=False)


def write_table(fields):
    lines = [
        "// Code generated by scripts/regen/graphql.py from specs/graphql.json. DO NOT EDIT.",
        "",
        "package cli",
        "",
        "var teamworkGraphQueries = []graphQuery{",
    ]
    for f in fields:
        args = ", ".join("{Name: %s, Type: %s}" % (go_string(a["name"]), go_string(a["type"])) for a in f["args"])
        lines.append("\t{Command: %s, Field: %s, Summary: %s, OptIn: %s, ForceDynamo: %s, Returns: %s, Args: []graphArg{%s}}," % (
            go_string(command_name(f["name"])), go_string(f["name"]), go_string(f["summary"]),
            go_string(f["optIn"]), "true" if f["forceDynamo"] else "false", go_string(f["returns"]), args))
    lines += ["}", ""]
    TABLE.write_text("\n".join(lines))
    subprocess.run(["gofmt", "-w", str(TABLE)], check=True)


def check(fields):
    old = {f["name"]: f for f in json.loads(SNAPSHOT.read_text())} if SNAPSHOT.exists() else {}
    new = {f["name"]: f for f in fields}
    added = sorted(new.keys() - old.keys())
    removed = sorted(old.keys() - new.keys())
    changed = sorted(k for k in new.keys() & old.keys() if new[k] != old[k])
    if not (added or removed or changed):
        return False
    print(f"## graphql (Teamwork Graph): {len(added)} added, {len(removed)} removed, {len(changed)} changed")
    for label, names in (("added", added), ("removed", removed), ("changed", changed)):
        for n in names:
            print(f"- {label}: `{n}`")
    print()
    return True


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("--write", "--check"):
        sys.exit(__doc__)
    fields = live_fields()
    if sys.argv[1] == "--check":
        sys.exit(1 if check(fields) else 0)
    SNAPSHOT.write_text(json.dumps(fields, indent=1) + "\n")
    write_table(fields)
    print(f"graphql: {len(fields)} Teamwork Graph queries -> {SNAPSHOT.relative_to(REPO)}, {TABLE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
